/* eslint-disable no-console */
const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const imagesRoot = path.join(projectRoot, 'assets', 'us', 'images');
const outFile = path.join(projectRoot, 'src', 'utils', 'usImageMap.js');

const walk = (dir) => {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
};

const toPosix = (p) => p.split(path.sep).join('/');

const main = () => {
  if (!fs.existsSync(imagesRoot)) {
    console.error(`Missing images root: ${imagesRoot}`);
    process.exit(1);
  }

  const allFiles = walk(imagesRoot).filter((f) => f.toLowerCase().endsWith('.png'));
  allFiles.sort((a, b) => a.localeCompare(b));

  const lines = [];
  lines.push('// Auto-generated. Do not edit by hand.');
  lines.push('// Generated by scripts/generate-us-image-map.js');
  lines.push('');
  lines.push('export const usImageMap = {');

  for (const abs of allFiles) {
    const relFromProject = toPosix(path.relative(projectRoot, abs));
    const relFromImagesRoot = toPosix(path.relative(imagesRoot, abs)); // e.g. warning-signs/foo.png
    const keyPath = `images/${relFromImagesRoot}`;
    const filename = path.basename(abs);

    // Key by full relative path used by quiz JSONs
    lines.push(`  ${JSON.stringify(keyPath)}: require(${JSON.stringify(`../../${relFromProject}`)}),`);
    // Also key by filename for compatibility with existing code paths
    lines.push(`  ${JSON.stringify(filename)}: require(${JSON.stringify(`../../${relFromProject}`)}),`);
  }

  lines.push('};');
  lines.push('');

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n') + '\n', 'utf8');
  console.log(`✅ Wrote ${allFiles.length} images → ${path.relative(projectRoot, outFile)}`);
};

main();


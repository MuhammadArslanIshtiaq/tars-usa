/* eslint-disable no-console */
const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const dataRoot = path.join(projectRoot, 'assets', 'us', 'data');
const outFile = path.join(projectRoot, 'src', 'utils', 'usQuizMap.js');

const walk = (dir) => {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
};

const toPosix = (p) => p.split(path.sep).join('/');

const getArg = (name, fallback) => {
  const idx = process.argv.findIndex((a) => a === `--${name}`);
  if (idx === -1) return fallback;
  const value = process.argv[idx + 1];
  return value || fallback;
};

const main = () => {
  if (!fs.existsSync(dataRoot)) {
    console.error(`Missing data root: ${dataRoot}`);
    process.exit(1);
  }

  const category = getArg('category', 'car');
  const state = getArg('state', 'Alabama');
  const includeTranslations = getArg('translations', 'true') !== 'false';
  const scopedRoot = path.join(dataRoot, category, state);

  if (!fs.existsSync(scopedRoot)) {
    console.error(`Missing scoped root: ${scopedRoot}`);
    process.exit(1);
  }

  const allJson = walk(scopedRoot).filter((f) => f.toLowerCase().endsWith('.json'));

  if (includeTranslations) {
    const translationsRoot = path.join(dataRoot, 'translations');
    if (fs.existsSync(translationsRoot)) {
      const langDirs = fs
        .readdirSync(translationsRoot, { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .map((d) => d.name);

      for (const lang of langDirs) {
        const translationScopedRoot = path.join(translationsRoot, lang, category, state);
        if (!fs.existsSync(translationScopedRoot)) continue;
        const translatedJson = walk(translationScopedRoot).filter((f) => f.toLowerCase().endsWith('.json'));
        allJson.push(...translatedJson);
      }
    }
  }

  allJson.sort((a, b) => a.localeCompare(b));

  const lines = [];
  lines.push('// Auto-generated. Do not edit by hand.');
  lines.push('// Generated by scripts/generate-us-quiz-map.js');
  lines.push('');
  lines.push('export const usQuizMap = {');

  for (const abs of allJson) {
    const relFromProject = toPosix(path.relative(projectRoot, abs));
    const relFromDataRoot = toPosix(path.relative(dataRoot, abs)); // e.g. car/Alabama/easy-practice-test-1.json
    lines.push(`  ${JSON.stringify(relFromDataRoot)}: require(${JSON.stringify(`../../${relFromProject}`)}),`);
  }

  lines.push('};');
  lines.push('');

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, lines.join('\n') + '\n', 'utf8');
  console.log(
    `✅ Wrote ${allJson.length} quiz JSONs (${category}/${state}${includeTranslations ? ' + translations' : ''}) → ${path.relative(projectRoot, outFile)}`
  );
};

main();


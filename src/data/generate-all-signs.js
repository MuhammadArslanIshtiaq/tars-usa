function generateSigns(signs, type, startId = 1) {
  return signs.map((filename, index) => {
    const title = filenameToTitle(filename);
    const description = generateDescription(title, type);
    const translations = generateTranslations(title, description, type);
    
    return {
      id: startId + index,
      type: type,
      title_en: title,
      description_en: description,
      image_path: `signs/${type === 'regulatory' ? 'regulatory-road-signs' : type === 'warning' ? 'warning-signs' : 'guide-signs'}/${filename}`,
      secondary_languages: {
        ur: translations.ur,
        ar: translations.ar,
        hi: translations.hi,
        bn: translations.bn
      }
    };
  });
}

